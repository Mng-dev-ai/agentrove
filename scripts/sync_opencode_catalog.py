#!/usr/bin/env python3
"""Regenerate backend/app/catalog/opencode.py from the models.dev catalog.

Usage: sync_opencode_catalog.py [SNAPSHOT.json]

Without a snapshot path the catalog is fetched from models.dev. Every
hand-maintained exception lives in opencode_catalog_overrides.toml; the previous
opencode.py is never read. Needs `ruff` on PATH (CI pins 0.15.0).
"""

import json
import os
import subprocess
import sys
import tomllib
import urllib.request
from pathlib import Path
from typing import Any, NamedTuple

REPO_ROOT = Path(__file__).resolve().parents[1]
OVERRIDES_PATH = Path(__file__).with_name("opencode_catalog_overrides.toml")
OUTPUT_PATH = REPO_ROOT / "backend" / "app" / "catalog" / "opencode.py"
RUFF_CONFIG = REPO_ROOT / "backend" / "pyproject.toml"
CATALOG_URL = "https://models.dev/api.json"
# Mirrors THINKING_MODE_ORDER in backend/app/services/acp/adapters.py; tiers
# outside it are dropped because the app cannot offer them.
EFFORT_LEVELS = ("none", "minimal", "low", "medium", "high", "xhigh", "max", "ultra")
HEADER = """\
# Generated by scripts/sync_opencode_catalog.py from models.dev and
# scripts/opencode_catalog_overrides.toml. Do not edit by hand.
from app.catalog.model_info import ModelInfo
from app.models.types import AgentKind

"""


class CatalogError(Exception):
    pass


class Entry(NamedTuple):
    display_name: str
    context_window: int
    legacy: bool
    effort_levels: tuple[str, ...]


def load_overrides(path: Path) -> dict[str, Any]:
    with path.open("rb") as file:
        return tomllib.load(file)


def fetch_catalog() -> dict[str, Any]:
    request = urllib.request.Request(
        CATALOG_URL, headers={"User-Agent": "agentrove-catalog-sync"}
    )
    with urllib.request.urlopen(request, timeout=60) as response:
        catalog: dict[str, Any] = json.load(response)
    return catalog


def effort_levels(model: dict[str, Any]) -> tuple[str, ...]:
    for option in model.get("reasoning_options") or ():
        if option["type"] == "effort":
            return tuple(v for v in option["values"] if v in EFFORT_LEVELS)
    return ()


def build_models(
    catalog: dict[str, Any], overrides: dict[str, Any]
) -> dict[str, Entry]:
    labels: dict[str, str] = overrides["providers"]
    names: dict[str, str] = overrides.get("display_names", {})
    legacy = {
        f"{provider}/{model_id}"
        for provider, model_ids in overrides.get("legacy", {}).items()
        for model_id in model_ids
    }
    found: dict[str, tuple[str, int, tuple[str, ...]]] = {}
    for provider in labels:
        if provider not in catalog:
            raise CatalogError(f"provider {provider!r} is missing from the catalog")
        live = 0
        for model_id, model in catalog[provider]["models"].items():
            context_window = model["limit"].get("context")
            if model.get("status") == "deprecated" or not context_window:
                continue
            live += 1
            found[f"{provider}/{model_id}"] = (
                model["name"],
                context_window,
                effort_levels(model),
            )
        if not live:
            raise CatalogError(f"provider {provider!r} has no usable models")
    for key, kept in overrides.get("keep", {}).items():
        if key.split("/", 1)[0] not in labels:
            raise CatalogError(f"keep entry {key!r} is outside the provider list")
        found.setdefault(
            key,
            (
                kept["name"],
                kept["context_window"],
                tuple(kept.get("effort_levels", ())),
            ),
        )
    if len(found) < overrides["min_models"]:
        raise CatalogError(
            f"only {len(found)} models, expected at least {overrides['min_models']}"
        )
    stale = sorted((legacy | set(names)) - set(found))
    if stale:
        print(f"overrides for models no longer listed: {stale}", file=sys.stderr)

    models: dict[str, Entry] = {}
    for provider, label in labels.items():
        for key in sorted(k for k in found if k.split("/", 1)[0] == provider):
            name, context_window, efforts = found[key]
            models[f"opencode:{key}"] = Entry(
                f"{names.get(key, name)} ({label})",
                context_window,
                key in legacy,
                efforts,
            )
    return models


def render(models: dict[str, Entry]) -> str:
    lines = [HEADER + "MODELS: dict[str, ModelInfo] = {"]
    for model_id, entry in models.items():
        window = entry.context_window
        args = [
            json.dumps(entry.display_name, ensure_ascii=False),
            "AgentKind.OPENCODE",
            f"{window:_}" if window >= 10_000 else str(window),
        ]
        if entry.legacy:
            args.append("legacy=True")
        if entry.effort_levels:
            # No trailing comma: ruff would treat it as magic and explode the tuple.
            levels = ", ".join(json.dumps(level) for level in entry.effort_levels)
            comma = "," if len(entry.effort_levels) == 1 else ""
            args.append(f"effort_levels=({levels}{comma})")
        lines.append(f"    {json.dumps(model_id)}: ModelInfo({', '.join(args)}),")
    lines.append("}\n")
    return "\n".join(lines)


def format_source(source: str) -> str:
    return subprocess.run(
        [
            "ruff",
            "format",
            "--config",
            str(RUFF_CONFIG),
            "--stdin-filename",
            str(OUTPUT_PATH),
            "-",
        ],
        input=source,
        capture_output=True,
        text=True,
        check=True,
    ).stdout


def main(argv: list[str]) -> int:
    if len(argv) > 1:
        print(__doc__, file=sys.stderr)
        return 2
    try:
        if argv:
            catalog = json.loads(Path(argv[0]).read_text(encoding="utf-8"))
        else:
            catalog = fetch_catalog()
        models = build_models(catalog, load_overrides(OVERRIDES_PATH))
        source = format_source(render(models))
    except (
        CatalogError,
        OSError,
        ValueError,
        LookupError,
        TypeError,
        subprocess.CalledProcessError,
    ) as error:
        print(f"OpenCode catalog not updated: {error}", file=sys.stderr)
        return 1
    # Replace atomically so an interrupted run never leaves a truncated catalog.
    temporary = OUTPUT_PATH.with_suffix(".py.tmp")
    temporary.write_text(source, encoding="utf-8")
    os.replace(temporary, OUTPUT_PATH)
    print(f"Wrote {len(models)} models to {OUTPUT_PATH.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
