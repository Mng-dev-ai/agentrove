#!/usr/bin/env node
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { extname, join, relative } from 'node:path';

const root = process.cwd();
const outDir = join(root, 'docs/generated');
const ignored = new Set([
  '.git',
  '.pytest_cache',
  '.ruff_cache',
  '.venv',
  'dist',
  'node_modules',
  'storage',
  'target',
  '__pycache__',
]);

const importantExts = new Set(['.ts', '.tsx', '.py', '.md', '.json', '.toml', '.yml', '.yaml']);

function walk(dir) {
  const entries = [];
  for (const name of readdirSync(dir).sort()) {
    if (ignored.has(name)) continue;
    const full = join(dir, name);
    const rel = relative(root, full);
    const stats = statSync(full);
    if (stats.isDirectory()) {
      entries.push(...walk(full));
      continue;
    }
    if (importantExts.has(extname(name)) || name === 'AGENTS.md' || name === 'CLAUDE.md') {
      entries.push(rel);
    }
  }
  return entries;
}

function safeRead(file) {
  try {
    return readFileSync(join(root, file), 'utf8');
  } catch {
    return '';
  }
}

function firstLines(file, limit = 3) {
  return safeRead(file)
    .split('\n')
    .slice(0, limit)
    .map((line) => line.trim())
    .filter(Boolean);
}

function tsSymbols(file) {
  const text = safeRead(file);
  const matches = [...text.matchAll(/export\s+(?:async\s+)?(?:function|const|class|interface|type|enum)\s+([A-Za-z0-9_]+)/g)];
  return matches.map((match) => match[1]).slice(0, 16);
}

function pySymbols(file) {
  const text = safeRead(file);
  const symbols = [];
  for (const line of text.split('\n')) {
    const match = line.match(/^(?:async\s+def|def|class)\s+([A-Za-z0-9_]+)/);
    if (match) symbols.push(match[1]);
  }
  return symbols.slice(0, 16);
}

function routeMarkers(file) {
  const text = safeRead(file);
  const markers = [...text.matchAll(/@router\.(get|post|put|patch|delete|websocket)\(([^)]*)\)/g)];
  return markers.map((match) => `${match[1]} ${match[2].split(',')[0]}`).slice(0, 16);
}

function groupByFolder(files, depth = 2) {
  const groups = new Map();
  for (const file of files) {
    const key = file.split('/').slice(0, depth).join('/');
    groups.set(key, (groups.get(key) ?? 0) + 1);
  }
  return [...groups.entries()].sort((a, b) => a[0].localeCompare(b[0]));
}

function table(rows, headers) {
  const body = rows.map((row) => `| ${row.map((cell) => String(cell).replaceAll('\n', ' ')).join(' | ')} |`);
  return [`| ${headers.join(' | ')} |`, `| ${headers.map(() => '---').join(' | ')} |`, ...body].join('\n');
}

function describeFiles(files) {
  return files.map((file) => {
    const ext = extname(file);
    const symbols = ext === '.py' ? pySymbols(file) : ['.ts', '.tsx'].includes(ext) ? tsSymbols(file) : [];
    const routes = ext === '.py' ? routeMarkers(file) : [];
    const summary = symbols.length ? symbols.join(', ') : routes.length ? routes.join(', ') : firstLines(file, 1).join(' ');
    return [file, summary || '-'];
  });
}

function writeGenerated(name, content) {
  const stamp = new Date().toISOString();
  writeFileSync(
    join(outDir, name),
    `<!-- GENERATED by scripts/generate-repo-map.mjs at ${stamp}. Do not edit by hand. -->\n\n${content.trim()}\n`,
  );
}

mkdirSync(outDir, { recursive: true });

const files = walk(root);
const frontend = files.filter((file) => file.startsWith('frontend/src/'));
const backend = files.filter((file) => file.startsWith('backend/app/') || file.startsWith('backend/tests/'));
const docs = files.filter((file) => file.startsWith('docs/'));
const agentEntrypoints = files.filter((file) =>
  [
    'AGENTS.md',
    'CLAUDE.md',
    'README.md',
    'frontend/package.json',
    'backend/pyproject.toml',
    'frontend/vite.config.ts',
    'frontend/src-tauri/Cargo.toml',
  ].includes(file),
);

writeGenerated(
  'repo-map.md',
  `# Repo Map

## Purpose

This generated map gives agents a compact overview before they open source files.
Read the MyBox docs first, then use this map to choose the smallest relevant
surface.

## Top-Level File Groups

${table(groupByFolder(files, 1).map(([group, count]) => [group, count]), ['Group', 'Files'])}

## Core Areas

${table(
  [
    ['frontend/src/components/chat', 'chat timeline, tools, inputs, model/persona/permission selectors'],
    ['frontend/src/components/sandbox', 'git, diff, terminal, secrets, sandbox panels'],
    ['frontend/src/components/layout', 'application shell, sidebar, title/header surfaces'],
    ['frontend/src/hooks/queries', 'TanStack Query API access'],
    ['frontend/src/store', 'Zustand UI, chat, model, settings state'],
    ['backend/app', 'FastAPI backend source'],
    ['frontend/src-tauri', 'macOS/Tauri desktop shell'],
    ['docs/mybox', 'MyBox fork authority'],
  ],
  ['Area', 'Meaning'],
)}

## Generated Map Files

- docs/generated/frontend-map.md
- docs/generated/backend-map.md
- docs/generated/agent-entrypoints.md
`,
);

writeGenerated(
  'frontend-map.md',
  `# Frontend Map

## Folder Counts

${table(groupByFolder(frontend, 3).map(([group, count]) => [group, count]), ['Folder', 'Files'])}

## Selected Source Files

${table(describeFiles(frontend.filter((file) => !file.includes('/assets/')).slice(0, 240)), ['File', 'Exports or first line'])}
`,
);

writeGenerated(
  'backend-map.md',
  `# Backend Map

## Folder Counts

${table(groupByFolder(backend, 3).map(([group, count]) => [group, count]), ['Folder', 'Files'])}

## Selected Source Files

${table(describeFiles(backend.slice(0, 240)), ['File', 'Symbols or routes'])}
`,
);

writeGenerated(
  'agent-entrypoints.md',
  `# Agent Entrypoints

## Startup Files

${table(describeFiles(agentEntrypoints), ['File', 'Summary'])}

## MyBox Authority Docs

${table(describeFiles(docs.filter((file) => file.startsWith('docs/mybox/'))), ['File', 'Summary'])}

## Agentrove Domain Docs

${table(describeFiles(docs.filter((file) => file.startsWith('docs/domains/'))), ['File', 'Summary'])}
`,
);

console.log(`Generated ${outDir}`);
